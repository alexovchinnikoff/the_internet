from playwright.sync_api import Page, Locator

class AddRemovePage:
# Класс - чертеж, шаблон (страницы). В нем описание элементов и что они умеют.
# Чертеж это не деталь. Его нельзя положить в коробку.
    def __init__(self, page: Page):
    #функция(аргументы) внутри класса. Вызываем не прямо, а так AddRemovePage(page):
    # 1. Видит: «Ага, хотят создать объект класса AddRemovePage».
    # 2. Автоматически вызывает метод __init__.
    # 3. Передает туда self (сам новый объект)
    # и page (то, что ты передал в скобках).
    # 4. Выполняет код внутри __init__ (сохраняет page, создает локаторы).
    # 5. Возвращает готовый объект.
    # AddRemovePage(page) это вызов функции класса AddRemovePage.__init__(page).
    # В данном случае — объект браузера (page).
    # .AddRemovePage(page) вызов конструктора это команда рабочему: «Сделай деталь по этому чертежу, используя вот этот станок (page) и вот эти материалы».
    # Фраза: «Возьми чертеж AddRemovePage, передай ему браузер page и создай реальный объект»
    # Мы берем созданный объект и кладем его в переменную my_page_object, чтобы потом с ним работать.
    # * Слева (page): имя переменной, которую мы передаем в функцию. * Справа (Page): это не библиотека, это класс (чертеж) из библиотеки playwright.sync_api.Это говорит: «В эту функцию можно передать только объект класса Page (то есть открытую вкладку браузера в Playwright). Если ты случайно передашь туда строку "hello" или список чисел, редактор кода (PyCharm) сразу подсветит ошибку красным».
    # self — это ссылка на сам объект, который мы создаем прямо сейчас. Представь, что ты строишь дом. self — это сам дом, который еще не достроен, но уже существует в проекте.
    # Когда мы пишем self.page = page, мы говорим: «В этот конкретный дом (объект) я кладу переменную page, чтобы она жила внутри него».
    # Без self переменная page существовала бы только внутри этой функции и исчезла бы сразу после её завершения. С self она становится свойством этого объекта.

        self.page = page
        # Правая часть (page): Это то, что нам дали снаружи.
        # Кто-то (в тесте) создал вкладку браузера и передал её сюда. Это «ключ от квартиры».
        # Левая часть (self.page): Это ячейка памяти внутри нашего нового объекта AddRemovePage.
        # Мы берем ключ и кладем его в карман этого объекта, чтобы он всегда был под рукой.
        # Зачем это нужно? Чтобы внутри любого метода этого класса (например, в click_add_element) мы могли обратиться к браузеру.
        # Локаторы (храним их как свойства класса)
        self.add_button = page.locator("button", has_text="Add Element")
        self.delete_buttons = page.locator("div#elements > button")
        self.header = page.locator("h3", has_text="Add/Remove Elements")

    # Методы-действия (то, что делает пользователь)
    def go_to(self):
        """Переходит на страницу"""
        self.page.goto("https://the-internet.herokuapp.com/add_remove_elements/")
        return self  # Возвращаем self, чтобы можно было делать цепочки (опционально)

    def click_add_element(self):
        """Нажимает кнопку добавления"""
        self.add_button.click()

    def click_first_delete(self):
        """Нажимает на первую кнопку Delete"""
        # Если кнопок нет, Playwright сам упадет с ошибкой ожидания, что правильно
        self.delete_buttons.first.click()

    # Методы-проверки (возвращают True/False или ничего, просто ждут)
    def expect_add_button_visible(self):
        expect(self.add_button).to_be_visible()

    def expect_delete_buttons_count(self, count: int):
        """Ждет, пока кнопок удаления станет ровно N"""
        expect(self.delete_buttons).to_have_count(count)

    def expect_no_delete_buttons(self):
        """Ждет, пока кнопок удаления не останется совсем (0)"""
        expect(self.delete_buttons).to_have_count(0) 